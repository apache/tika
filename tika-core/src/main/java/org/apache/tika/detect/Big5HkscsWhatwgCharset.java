    /** 1 + index into VALUES, by {@code ((lead & 0x7F) << 8) | trail}; 0 = not patched. */
    private static final short[] SLOT = new short[0x8000];

    static {
        for (int i = 0; i < PAIRS.length; i++) {
            SLOT[PAIRS[i] & 0x7FFF] = (short) (i + 1);
        }
    }

    private Big5HkscsWhatwgCharset() {
        super(NAME, null);
    }

    /** The patched pairs, as {@code lead << 8 | trail}. */
    static int[] patchedPairs() {
        return PAIRS.clone();
    }

    /** The WHATWG decode of a patched pair, or {@code null}. */
    static String patch(int lead, int trail) {
        int s = SLOT[((lead & 0x7F) << 8) | (trail & 0xFF)];
        return lead >= 0x80 && s != 0 ? VALUES[s - 1] : null;
    }

    @Override
    public boolean contains(Charset cs) {
        return cs == this || BASE.contains(cs);
    }

    @Override
    public CharsetDecoder newDecoder() {
        return new Decoder(this);
    }

    @Override
    public CharsetEncoder newEncoder() {
        return BASE.newEncoder();
    }

    private static final class Decoder extends CharsetDecoder {

        private final CharsetDecoder base = BASE.newDecoder();

        private Decoder(Charset cs) {
            super(cs, BASE.newDecoder().averageCharsPerByte(), BASE.newDecoder().maxCharsPerByte());
        }

        @Override
        protected CoderResult decodeLoop(ByteBuffer in, CharBuffer out) {
            while (true) {
                int start = in.position();
                int limit = in.limit();
                // Tokenize as the JDK does: a high byte always takes the next byte with it, so
                // a patched pair is only ever seen at a token boundary.
                int i = start;
                String value = null;
                while (i < limit) {
                    int b = in.get(i) & 0xFF;
                    if (b < 0x80) {
                        i++;
                        continue;
                    }
                    if (i + 1 == limit) {
                        break;
                    }
                    value = patch(b, in.get(i + 1));
                    if (value != null) {
                        break;
                    }
                    i += 2;
                }
                if (i > start) {
                    ByteBuffer run = in.duplicate();
                    run.limit(i);
                    CoderResult cr = base.decode(run, out, false);
                    in.position(run.position());
                    if (cr.isError() || cr.isOverflow() || run.hasRemaining()) {
                        return cr;
                    }
                }
                if (value == null) {
                    return CoderResult.UNDERFLOW;
                }
                if (out.remaining() < value.length()) {
                    return CoderResult.OVERFLOW;
                }
                out.put(value);
                in.position(i + 2);
            }
        }

        @Override
        protected void implReset() {
            base.reset();
        }
    }
